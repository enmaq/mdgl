#!/usr/bin/env node
// Generates src/unicode-tables.ts from the primary Unicode 15.0.0 data files, fetched flat from
// https://www.unicode.org/Public/15.0.0/ucd/{auxiliary/GraphemeBreakProperty.txt,EastAsianWidth.txt,
// UnicodeData.txt,DerivedCoreProperties.txt,emoji/emoji-data.txt,emoji/emoji-variation-sequences.txt}
// Usage: node scripts/gen-unicode.js UCD_DIR   (UCD_DIR holds those files by basename)
const fs = require('fs');
const path = require('path');
const dir = process.argv[2];
const rd = (f) => fs.readFileSync(path.join(dir, f), 'utf8');
const rows = (f, re) => {
  const out = [];
  for (const l of rd(f).split('\n')) {
    const m = l.replace(/#.*/, '').trim().match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(.+)$/);
    if (!m) continue;
    const v = m[3].trim();
    if (re && !re.test(v)) continue;
    out.push([parseInt(m[1], 16), parseInt(m[2] || m[1], 16), v]);
  }
  return out;
};
const GCB = ['Prepend', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT'];
const merge = (rs) => {
  rs.sort((a, b) => a[0] - b[0]);
  const o = [];
  for (const [s, e, c] of rs) {
    const p = o[o.length - 1];
    if (p && p[2] === c && p[1] + 1 === s) p[1] = e; else o.push([s, e, c]);
  }
  return o;
};
const flat = (rs) => rs.flatMap(([s, e, c]) => [s, e, c]).join(',');
const gcb = merge(rows('GraphemeBreakProperty.txt').map(([s, e, v]) => [s, e, GCB.indexOf(v)]));
if (gcb.some((r) => r[2] < 0)) throw new Error('unknown GCB value');
const pict = merge(rows('emoji-data.txt', /^Extended_Pictographic$/).map(([s, e]) => [s, e, 0]));
const dicp = merge(rows('DerivedCoreProperties.txt', /^Default_Ignorable_Code_Point$/).map(([s, e]) => [s, e, 0]));
// base code points of single-rune 'emoji style' (VS16) variation sequences
const vs16 = merge(rd('emoji-variation-sequences.txt').split('\n').map((l) => l.match(/^([0-9A-F]+) FE0F\s*;\s*emoji style/)).filter(Boolean).map((m) => [parseInt(m[1], 16), parseInt(m[1], 16), 0]));
const wide = merge(rows('EastAsianWidth.txt', /^[WF]$/).map(([s, e]) => [s, e, 0]));
// General_Category M* from UnicodeData.txt (handles First/Last range pairs)
const marks = [];
let first = null;
for (const l of rd('UnicodeData.txt').split('\n')) {
  const f = l.split(';');
  if (f.length < 3) continue;
  const cp = parseInt(f[0], 16);
  if (/, First>$/.test(f[1])) { first = cp; continue; }
  const s = /, Last>$/.test(f[1]) ? first : cp;
  if (/^M/.test(f[2])) marks.push([s, cp, 0]);
}
const mk = merge(marks);
const crypto = require('crypto');
const files = ['GraphemeBreakProperty.txt', 'EastAsianWidth.txt', 'UnicodeData.txt', 'DerivedCoreProperties.txt', 'emoji-data.txt', 'emoji-variation-sequences.txt'];
const prov = files.map((f) => `${f} sha256=${crypto.createHash('sha256').update(fs.readFileSync(path.join(dir, f))).digest('hex')}`);
for (const f of files.slice(0, 1)) if (!/15\.0\.0/.test(rd(f).split('\n')[0])) throw new Error(f + ' is not Unicode 15.0.0');
const out = `// GENERATED by scripts/gen-unicode.js -- do not edit.
// Unicode 15.0.0 Character Database + Emoji 15.0 data, fetched from https://www.unicode.org/Public/15.0.0/ucd/.
// Inputs: ${prov.join('; ')}.
// Data (c) 1991-2022 Unicode, Inc. Unicode License V3 (https://www.unicode.org/license.txt); see ts/UNICODE-LICENSE.txt.
// Flat [start,end,class] triples.
export const GCB_NAMES = ${JSON.stringify(GCB)} as const;
export const GCB: number[] = [${flat(gcb)}];
export const EXT_PICT: number[] = [${flat(pict)}];
export const WIDE: number[] = [${flat(wide)}];
export const MARK: number[] = [${flat(mk)}];
export const IGNORABLE: number[] = [${flat(dicp)}];
export const VS16_BASE: number[] = [${flat(vs16)}];
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'unicode-tables.ts'), out);
console.log('ranges', { gcb: gcb.length, pict: pict.length, wide: wide.length, mark: mk.length, dicp: dicp.length, vs16: vs16.length });
