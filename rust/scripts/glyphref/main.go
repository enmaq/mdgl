package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"

	"github.com/enmaq/mdgl/go/model"
)

func main() {
	w := bufio.NewWriter(os.Stdout)
	defer w.Flush()
	emit := func(rs ...rune) {
		var hex, out []string
		for _, r := range rs {
			hex = append(hex, fmt.Sprintf("%X", r))
		}
		for _, g := range model.Glyphs(string(rs)) {
			out = append(out, fmt.Sprintf("%X", g))
		}
		fmt.Fprintf(w, "%s\t%s\n", strings.Join(hex, " "), strings.Join(out, " "))
	}
	fixed := [][]rune{
		{0x1F1FA, 0x1F1F8}, {0x1F1FA}, {0x1F1FA, 0x1F1F8, 0x1F1E9}, {0x1F1FA, 0x1F1F8, 0x1F1E9, 0x1F1EA},
		{0x2764}, {0x2764, 0xFE0F}, {0x2764, 0xFE0E}, {0x263A, 0xFE0F}, {0x00A9, 0xFE0F}, {0x0023, 0xFE0F, 0x20E3}, {0x0031, 0xFE0F, 0x20E3}, {0x0031, 0x20E3},
		{0x200B}, {0x200C}, {0x200D}, {0x2060}, {0xFEFF}, {0x61, 0x200B, 0x62}, {0x200D, 0x61},
		{0x0301}, {0x0301, 0x61}, {0x0301, 0x0302}, {0x61, 0x0301}, {0x0600, 0x61}, {0x0600}, {0x0600, 0x0301},
		{0x1F468, 0x200D, 0x1F469, 0x200D, 0x1F467}, {0x1F469, 0x200D, 0x2764, 0xFE0F, 0x200D, 0x1F468}, {0x1F3F4, 0xE0067, 0xE0062, 0xE0065, 0xE006E, 0xE0067, 0xE007F},
		{0x1F44D, 0x1F3FD}, {0x1F44D}, {0x4E2D}, {0xFF21}, {0xFF76, 0xFF9E}, {0x1100, 0x1161, 0x11A8}, {0xAC00}, {0x0915, 0x093E}, {0x0928, 0x094D, 0x0924},
		{0x0E01, 0x0E31}, {0x0628, 0x064E}, {0x0020}, {0x0009}, {0x00A0}, {0x3000}, {0x61, 0x62},
	}
	for _, f := range fixed {
		emit(f...)
	}
	for r := rune(0x20); r < 0x30000; r++ {
		if r >= 0xD800 && r < 0xE000 || r < 0x20 || r >= 0x7F && r < 0xA0 {
			continue
		}
		emit(r)
		if r%7 == 0 {
			emit(r, 0xFE0F)
			emit(r, 0x0301)
		}
	}
}
