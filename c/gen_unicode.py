#!/usr/bin/env python3
"""Generates mdgl_unicode.h from the rivo/uniseg v0.4.7 property tables.

Usage: gen_unicode.py PATH/TO/uniseg@v0.4.7 > mdgl_unicode.h

mark_table/print_table come from Go's unicode.IsMark/IsPrint (gen_cat.go; BSD-3, Unicode 15.0.0).
The uniseg tables are generated from Unicode 15.0.0 data (GraphemeBreakProperty,
emoji-data Extended_Pictographic, EastAsianWidth) and uniseg is MIT licensed
(Copyright (c) 2019 Oliver Kuederle); Unicode data is under the Unicode License
(https://www.unicode.org/license.html). Using the reference implementation's own
tables keeps the C segmentation identical to the Go reference.
"""
import re, subprocess, sys

d = sys.argv[1]
G = ["Any", "Prepend", "CR", "LF", "Control", "Extend", "RegionalIndicator", "SpacingMark", "L", "V", "T", "LV", "LVT", "ZWJ", "ExtendedPictographic"]
E = ["N", "Na", "A", "W", "H", "F"]

def table(fname, var, names, prefix):
    s = open(f"{d}/{fname}").read()
    body = s[s.index(var + " = "):]
    body = body[:body.index("\n}\n")]
    rows = []
    for m in re.finditer(r"\{(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+), pr(\w+)\}", body):
        rows.append((int(m.group(1), 16), int(m.group(2), 16), names.index(m.group(3)) if names else 0))
    rows.sort()
    return rows

def emit(name, rows, cty="uint8_t"):
    print(f"static const struct {{ uint32_t lo, hi; {cty} v; }} {name}[] = {{")
    line = ""
    for lo, hi, v in rows:
        item = "{0x%X,0x%X,%d}," % (lo, hi, v)
        if len(line) + len(item) > 100:
            print(line); line = ""
        line += item
    print(line)
    print("};")

gr = table("graphemeproperties.go", "graphemeCodePoints", G, "gb")
ea = table("eastasianwidth.go", "eastAsianWidth", E, "ea")
ep = table("emojipresentation.go", "emojiPresentation", ["", "EmojiPresentation"], "ep")
print("/* Generated by gen_unicode.py from rivo/uniseg v0.4.7 (Unicode 15.0.0). DO NOT EDIT.\n * Tables: MIT (c) 2019 Oliver Kuederle; Unicode data under https://www.unicode.org/license.html */")
print("#ifndef MDGL_UNICODE_H\n#define MDGL_UNICODE_H\n#include <stdint.h>")
print("enum { GB_Any, GB_Prepend, GB_CR, GB_LF, GB_Control, GB_Extend, GB_RI, GB_SpacingMark, GB_L, GB_V, GB_T, GB_LV, GB_LVT, GB_ZWJ, GB_ExtPict };")
print("enum { EA_N, EA_Na, EA_A, EA_W, EA_H, EA_F };")
emit("gb_table", gr); emit("ea_table", ea); emit("ep_table", ep)
sys.stdout.flush()
sys.stdout.write(subprocess.run(["go", "run", "gen_cat.go"], check=True, capture_output=True, text=True, cwd=__import__("os").path.dirname(__import__("os").path.abspath(__file__))).stdout)
print("#endif")
